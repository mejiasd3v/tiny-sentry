import { mkdir } from "node:fs/promises";

const result = await Bun.build({ entrypoints: ["src/sourcemaps/uploader.ts"], target: "node", format: "esm", minify: false,
  banner: "// Generated by bun run build:uploader. Source: src/sourcemaps/uploader.ts. MIT licensed.\n" });
if (!result.success || result.outputs.length !== 1) throw new Error(`Uploader build failed: ${result.logs}`);
const content = await result.outputs[0]!.text();
const path = "tools/upload-sourcemaps.mjs";
if (process.argv.includes("--check")) {
  if (!await Bun.file(path).exists() || await Bun.file(path).text() !== content) throw new Error("Standalone uploader is stale; run bun run build:uploader");
} else { await mkdir("tools", { recursive: true }); await Bun.write(path, content); }
